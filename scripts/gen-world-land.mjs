// Regenerates lib/worldLandGrid.ts from real Earth coastline data — the
// contact globe (components/GlobeContact.tsx) reads that file to decide
// which of its dots sit on land. Source: Natural Earth's 1:110,000,000
// scale land data (public domain), via the world-atlas project's
// pre-built TopoJSON (https://github.com/topojson/world-atlas). Run with
// `npm run gen-world-land` — only needs to be rerun if a different
// resolution or source is ever wanted; the output is committed like any
// other source file, not generated at build time.
import fs from "fs";
import * as topojson from "topojson-client";

const SOURCE_URL = "https://unpkg.com/world-atlas@2/land-110m.json";
const COLS = 360; // 1-degree longitude resolution
const ROWS = 180; // 1-degree latitude resolution
const OUT_PATH = new URL("../lib/worldLandGrid.ts", import.meta.url);

function pointInRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const intersect = yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

function isLandAt(polygons, lon, lat) {
  for (const poly of polygons) {
    if (pointInRing(lon, lat, poly[0])) {
      let inHole = false;
      for (let h = 1; h < poly.length; h++) {
        if (pointInRing(lon, lat, poly[h])) inHole = true;
      }
      if (!inHole) return true;
    }
  }
  return false;
}

async function main() {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`Failed to fetch ${SOURCE_URL}: ${res.status}`);
  const topo = await res.json();
  const geo = topojson.feature(topo, topo.objects.land);
  const polygons = geo.features[0].geometry.coordinates;

  const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
  let landCount = 0;
  for (let row = 0; row < ROWS; row++) {
    const lat = 90 - row - 0.5;
    for (let col = 0; col < COLS; col++) {
      const lon = col - 180 + 0.5;
      if (isLandAt(polygons, lon, lat)) {
        const idx = row * COLS + col;
        bits[idx >> 3] |= 1 << (idx & 7);
        landCount++;
      }
    }
  }

  const b64 = Buffer.from(bits).toString("base64");
  const out = `// Generated by scripts/gen-world-land.mjs — do not hand-edit.
// Source: Natural Earth 1:110,000,000 land data (public domain), via
// world-atlas's land-110m.json (https://github.com/topojson/world-atlas).
// A real 1-degree land/ocean grid rasterized from actual coastline
// polygons, not a hand-approximated shape — used by lib/worldLand.ts for
// the contact globe (components/GlobeContact.tsx).
export const WORLD_GRID_COLS = ${COLS};
export const WORLD_GRID_ROWS = ${ROWS};
export const WORLD_GRID_B64 = "${b64}";
`;
  fs.writeFileSync(OUT_PATH, out);
  console.log(`Wrote ${OUT_PATH.pathname} — ${landCount}/${COLS * ROWS} land cells (${((landCount / (COLS * ROWS)) * 100).toFixed(1)}%)`);
}

main();
